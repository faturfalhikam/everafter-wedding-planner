async function seed() {
  console.log('Calculating verification stats...');
  const totalBudget = budget_categories.reduce((s, c) => s + c.allocatedBudget, 0);
  const totalPaid = vendors.reduce(
    (sum, v) => sum + v.payments.reduce((pSum: number, p: any) => pSum + p.amount, 0),
    0
  );
  const totalCommitted = vendors.reduce((sum, v) => {
    if (v.status === 'booked') {
      const paid = v.payments.reduce((pSum: number, p: any) => pSum + p.amount, 0);
      return sum + Math.max(0, v.totalContractValue - paid);
    }
    return sum;
  }, 0);

  console.log(`Total Budget: Rp ${totalBudget.toLocaleString('id-ID')}`);
  console.log(`Total Paid: Rp ${totalPaid.toLocaleString('id-ID')}`);
  console.log(`Total Committed: Rp ${totalCommitted.toLocaleString('id-ID')}`);
  console.log(`Remaining: Rp ${(totalBudget - totalPaid - totalCommitted).toLocaleString('id-ID')}`);

  const payload = {
    id: eventId,
    share_code: shareCode,
    title: 'Lamaran Fatur & Tria',
    event,
    tasks,
    budget_categories,
    vendors,
    guests,
    partner_user,
    updated_at: new Date().toISOString(),
  };

  const { data, error } = await supabase
    .from('wedding_plans')
    .upsert(payload, { onConflict: 'id' })
    .select();

  if (error) {
    console.error('Error seeding to Supabase:', error);
    process.exit(1);
  }

  console.log('Successfully replaced database with fatur.csv data!');
  console.log('Updated record ID:', data?.[0]?.id, 'Share code:', data?.[0]?.share_code);
}

seed();
